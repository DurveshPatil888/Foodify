export const getCategoryImage = (name) => {
  const key = (name || '').toLowerCase();
  const match = CATEGORY_IMAGES.find(([label]) => key.includes(label));
  if (match) return match[1];
  let hash = 0;
  for (let i = 0; i < key.length; i++) {
    hash = (hash + key.charCodeAt(i) * (i + 1)) % FALLBACK_FOOD_IMAGES.length;
  }
  return FALLBACK_FOOD_IMAGES[hash];
};
